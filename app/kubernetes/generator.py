"""Deterministic Kubernetes manifest generation (no LLM). Manifests are NEVER applied by this tool.

Generated per application component: Deployment, Service, ConfigMap (only when there is data), Secret *template*
(placeholder values only), optional Ingress, PVC (only when the Dockerfile declares VOLUME), and an HPA (autoscaling/v2).
Backing services (databases, caches) are intentionally not generated: run them as managed/separate services.
Resource figures are starting points, not measurements.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path
from typing import Callable, Optional

from pydantic import BaseModel, Field

from app.analyzer.models import ProjectAnalysis, ProjectUnit
from app.docker.docker_validator import exposed_ports, parse_instructions
from app.utils import yamlish
from app.utils.credcheck import has_embedded_credential
from app.utils.security import ensure_within

SECRET_HINT = re.compile(r"(?i)(password|passwd|secret|token|api[_-]?key|private[_-]?key|credential)")
CONNECTION_SECRETS = {"DATABASE_URL", "DB_URL", "SQLALCHEMY_DATABASE_URI", "REDIS_URL", "MONGO_URL", "MONGODB_URI",
                      "MONGO_URI", "CACHE_URL", "BROKER_URL", "CELERY_BROKER_URL"}  # usually embed credentials
PLACEHOLDER = "REPLACE_ME"
DNS_LABEL = re.compile(r"^[a-z0-9]([-a-z0-9]*[a-z0-9])?$")
# (cpu request, mem request, cpu limit, mem limit) - starting points only
RESOURCES = {"Python": ("100m", "128Mi", "500m", "512Mi"), "JavaScript": ("100m", "128Mi", "500m", "512Mi"),
             "Java": ("250m", "512Mi", "1000m", "1Gi"), "Go": ("50m", "64Mi", "250m", "256Mi"),
             "PHP": ("100m", "128Mi", "500m", "512Mi"), "Ruby": ("100m", "192Mi", "500m", "512Mi")}
DEFAULT_RESOURCES = ("100m", "128Mi", "500m", "512Mi")


class ManifestSet(BaseModel):
    component: str
    docs: list[dict] = Field(default_factory=list)

    def file_map(self) -> dict[str, dict]:
        out: dict[str, dict] = {}
        for d in self.docs:
            out[f"{self.component}/{d['kind'].lower()}.yaml"] = d
        return out


class K8sResult(BaseModel):
    sets: list[ManifestSet] = Field(default_factory=list)
    notes: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)

    @property
    def docs(self) -> list[dict]:
        return [d for s in self.sets for d in s.docs]

    @property
    def files(self) -> dict[str, str]:
        out = {}
        for s in self.sets:
            for path, doc in s.file_map().items():
                out[path] = HEADER + yamlish.dump(doc)
        return out

    @property
    def combined(self) -> str:
        return HEADER + yamlish.dump_all(self.docs)


class K8sValidation(BaseModel):
    ok: bool
    errors: list[str] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    kubectl_checked: bool = False


HEADER = ("# Generated by the AI DevOps Agent. Review before applying; this tool never deploys.\n")


def k8s_name(text: str) -> str:
    n = re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")[:50].strip("-")
    return n or "app"


def _cpu_milli(v: str) -> float:
    return float(v[:-1]) if v.endswith("m") else float(v) * 1000


def _mem_mi(v: str) -> float:
    m = re.fullmatch(r"(\d+(?:\.\d+)?)(Ki|Mi|Gi)?", v)
    if not m:
        return -1
    return float(m.group(1)) * {"Ki": 1 / 1024, "Mi": 1, "Gi": 1024, None: 1 / (1024 * 1024)}[m.group(2)]


def _dockerfile_facts(dockerfile: str) -> tuple[list[str], Optional[int]]:
    """(VOLUME paths, numeric uid of the final USER or None)."""
    if not dockerfile.strip():
        return [], None
    instrs, _ = parse_instructions(dockerfile)
    volumes: list[str] = []
    for i in instrs:
        if i.name == "VOLUME":
            raw = i.args.strip()
            volumes += re.findall(r"[\"']?(/[^\s\"',\]]+)", raw)
    users = [i.args.strip() for i in instrs if i.name == "USER"]
    uid = None
    if users:
        m = re.match(r"(\d+)(?::\d+)?$", users[-1])
        uid = int(m.group(1)) if m and int(m.group(1)) != 0 else None
    return volumes, uid


def load_unit_dockerfiles(analysis: ProjectAnalysis, project_dir: Path | str) -> dict[str, str]:
    """Read each component's existing Dockerfile (path -> text); components without one are omitted."""
    root = Path(project_dir)
    out: dict[str, str] = {}
    for u in analysis.units:
        f = root / u.path / "Dockerfile"
        if f.is_file() and not f.is_symlink() and f.stat().st_size < 200_000:
            out[u.path] = f.read_text(encoding="utf-8", errors="replace")
    return out


def _labels(name: str, analysis_name: str) -> dict:
    return {"app.kubernetes.io/name": name, "app.kubernetes.io/part-of": k8s_name(analysis_name),
            "app.kubernetes.io/managed-by": "ai-devops-agent"}


def generate_manifests(analysis: ProjectAnalysis, *, image: Optional[str] = None, dockerfile: str = "",
                       namespace: Optional[str] = None, ingress_host: Optional[str] = None, health_path: Optional[str] = None,
                       replicas: int = 2, units_dockerfiles: Optional[dict[str, str]] = None) -> K8sResult:
    res = K8sResult()
    def _df(u: ProjectUnit) -> str:
        return (units_dockerfiles or {}).get(u.path, dockerfile)

    def _listens(u: ProjectUnit) -> bool:
        return bool(u.ports or exposed_ports(_df(u)))

    units = [u for u in analysis.units if not u.workspace_root and u.role in ("backend", "frontend", "fullstack", "unknown")
             and u.language != "unknown" and _listens(u)]
    if not units and analysis.primary_unit and _listens(analysis.primary_unit):
        units = [analysis.primary_unit]
    if not units:
        raise ValueError("No application component with a detectable listening port; cannot generate a Deployment.")
    multi = len(units) > 1
    if analysis.services:
        res.notes.append("Backing services detected (" + ", ".join(sorted(analysis.services)) + ") are NOT generated: "
                         "use managed services or deploy them separately and put their addresses in the Secret/ConfigMap.")
    if not 1 <= replicas <= 50:
        raise ValueError("replicas must be between 1 and 50")

    for u in units:
        name = k8s_name(u.path if multi and u.path not in (".", "") else analysis.name)
        df = (units_dockerfiles or {}).get(u.path, dockerfile)
        volumes, uid = _dockerfile_facts(df)
        port = u.ports[0] if u.ports else exposed_ports(df)[0]
        exposed = exposed_ports(df)
        if exposed and exposed[0] != port:
            res.warnings.append(f"{name}: the source suggests port {port} but the Dockerfile EXPOSEs {exposed[0]}; "
                                f"using {exposed[0]}. Check which one the app really binds.")
            port = exposed[0]
        img = image or f"{name}:ai-generated"
        if multi and image:
            img = f"{image.rsplit(':', 1)[0]}-{name}:{image.rsplit(':', 1)[1] if ':' in image.split('/')[-1] else 'ai-generated'}"
        if image is None:
            res.notes.append(f"{name}: image '{img}' is a local name; push it to a registry your cluster can pull from "
                             "(or load it into kind/minikube) and set the image.")
        if img.endswith(":latest") or ":" not in img.split("/")[-1]:
            res.warnings.append(f"{name}: image '{img}' is unpinned; use an explicit version tag.")
        labels = _labels(name, analysis.name)
        sel = {"app.kubernetes.io/name": name}
        meta = lambda n, extra=None: {"name": n, "labels": dict(labels), **({"namespace": namespace} if namespace else {}),  # noqa: E731
                                      **(extra or {})}
        docs: list[dict] = []

        # environment: secrets -> Secret template; derived non-secret hosts -> ConfigMap; the rest only as notes
        secret_keys = [v for v in analysis.env_vars if SECRET_HINT.search(v) or v.upper() in CONNECTION_SECRETS]
        config: dict[str, str] = {}
        kinds = {k.lower() for k in analysis.services}
        if "PORT" in analysis.env_vars:
            config["PORT"] = str(port)
        if "REDIS_HOST" in analysis.env_vars and "redis" in kinds:
            config["REDIS_HOST"] = "redis"
        leftover = [v for v in analysis.env_vars if v not in secret_keys and v not in config]
        if leftover:
            res.notes.append(f"{name}: non-secret variables detected without a known value (add them to the ConfigMap): "
                             + ", ".join(leftover[:12]))
        env_from = []
        if config:
            docs.append({"apiVersion": "v1", "kind": "ConfigMap", "metadata": meta(f"{name}-config"), "data": config})
            env_from.append({"configMapRef": {"name": f"{name}-config"}})
        if secret_keys:
            docs.append({"apiVersion": "v1", "kind": "Secret",
                         "metadata": meta(f"{name}-secrets", {"annotations": {
                             "ai-devops-agent/note": f"Template: replace every {PLACEHOLDER} before applying; never commit real values."}}),
                         "type": "Opaque", "stringData": {k: PLACEHOLDER for k in secret_keys}})
            env_from.append({"secretRef": {"name": f"{name}-secrets"}})
            res.notes.append(f"{name}: the Secret contains placeholders only. Prefer `kubectl create secret` or a secret "
                             "manager over committing values.")

        # pod spec
        cpu_r, mem_r, cpu_l, mem_l = RESOURCES.get(u.language, DEFAULT_RESOURCES)
        container: dict = {
            "name": name, "image": img, "imagePullPolicy": "IfNotPresent",
            "ports": [{"name": "http", "containerPort": port}],
            "resources": {"requests": {"cpu": cpu_r, "memory": mem_r}, "limits": {"cpu": cpu_l, "memory": mem_l}},
            "securityContext": {"allowPrivilegeEscalation": False, "capabilities": {"drop": ["ALL"]}}}
        if env_from:
            container["envFrom"] = env_from
        probe = ({"httpGet": {"path": health_path, "port": "http"}} if health_path else {"tcpSocket": {"port": "http"}})
        container["startupProbe"] = {**probe, "periodSeconds": 5, "failureThreshold": 30}
        container["readinessProbe"] = {**probe, "periodSeconds": 10, "timeoutSeconds": 3, "failureThreshold": 3}
        container["livenessProbe"] = {**probe, "periodSeconds": 20, "timeoutSeconds": 3, "failureThreshold": 3}
        if not health_path:
            res.notes.append(f"{name}: probes check the TCP port only; pass a health path for HTTP probes.")
        pod_sec: dict = {"seccompProfile": {"type": "RuntimeDefault"}}
        if uid:
            pod_sec.update({"runAsNonRoot": True, "runAsUser": uid})
        elif df.strip():
            res.warnings.append(f"{name}: the Dockerfile has no numeric non-root USER, so runAsNonRoot is not enforced "
                                "(Kubernetes cannot verify named users). Use `USER 10001` for enforcement.")
        spec: dict = {"containers": [container], "securityContext": pod_sec, "automountServiceAccountToken": False}
        stateful = bool(volumes)
        if stateful:
            container["volumeMounts"] = [{"name": "data", "mountPath": volumes[0]}]
            spec["volumes"] = [{"name": "data", "persistentVolumeClaim": {"claimName": f"{name}-data"}}]
            docs.append({"apiVersion": "v1", "kind": "PersistentVolumeClaim", "metadata": meta(f"{name}-data"),
                         "spec": {"accessModes": ["ReadWriteOnce"], "resources": {"requests": {"storage": "1Gi"}}}})
            res.notes.append(f"{name}: the Dockerfile declares VOLUME {', '.join(volumes)}; only the first path is mounted on "
                             "a 1Gi ReadWriteOnce PVC, so replicas are limited to 1 and no HPA is generated.")
            if len(volumes) > 1:
                res.warnings.append(f"{name}: additional VOLUME paths ({', '.join(volumes[1:])}) are not mounted.")
        n_replicas = 1 if stateful else replicas
        dep: dict = {"apiVersion": "apps/v1", "kind": "Deployment", "metadata": meta(name),
                     "spec": {"replicas": n_replicas, "selector": {"matchLabels": sel},
                              "template": {"metadata": {"labels": {**labels}}, "spec": spec}}}
        if stateful:
            dep["spec"]["strategy"] = {"type": "Recreate"}
        docs.insert(0, dep)
        docs.append({"apiVersion": "v1", "kind": "Service", "metadata": meta(name),
                     "spec": {"type": "ClusterIP", "selector": sel, "ports": [{"name": "http", "port": port,
                                                                                 "targetPort": "http"}]}})
        if ingress_host and u.role != "unknown":
            docs.append({"apiVersion": "networking.k8s.io/v1", "kind": "Ingress", "metadata": meta(name),
                         "spec": {"rules": [{"host": ingress_host, "http": {"paths": [{
                             "path": "/", "pathType": "Prefix",
                             "backend": {"service": {"name": name, "port": {"name": "http"}}}}]}}]}})
            res.notes.append(f"{name}: Ingress needs an ingress controller; no ingressClassName or TLS is set (TLS needs a "
                             "certificate Secret you provide).")
        if not stateful:
            docs.append({"apiVersion": "autoscaling/v2", "kind": "HorizontalPodAutoscaler", "metadata": meta(name),
                         "spec": {"scaleTargetRef": {"apiVersion": "apps/v1", "kind": "Deployment", "name": name},
                                  "minReplicas": n_replicas, "maxReplicas": max(n_replicas * 3, 3),
                                  "metrics": [{"type": "Resource", "resource": {"name": "cpu", "target": {
                                      "type": "Utilization", "averageUtilization": 70}}}]}})
        res.sets.append(ManifestSet(component=name, docs=docs))
    res.notes.append("Resource requests/limits are starting points, not measurements; the HPA needs metrics-server.")
    return res


# ----------------------------------------------------------------------------- validation
def validate_manifests(docs: list[dict], *, runner: Callable[..., "subprocess.CompletedProcess[str]"] = subprocess.run,
                       which: Callable[[str], Optional[str]] = shutil.which, use_kubectl: bool = True,
                       yaml_text: Optional[str] = None) -> K8sValidation:
    errors: list[str] = []
    warnings: list[str] = []
    by_kind: dict[tuple[str, str], dict] = {}
    for d in docs:
        if not isinstance(d, dict) or not d.get("apiVersion") or not d.get("kind") or not (d.get("metadata") or {}).get("name"):
            errors.append("Every resource needs apiVersion, kind and metadata.name.")
            continue
        n = d["metadata"]["name"]
        if not DNS_LABEL.match(n) or len(n) > 63:
            errors.append(f"{d['kind']}/{n}: name is not a valid DNS-1123 label.")
        by_kind[(d["kind"], n)] = d
    if has_embedded_credential(docs):
        errors.append("A value looks like an embedded credential.")
    for (kind, n), d in by_kind.items():
        if kind == "Secret":
            for k, v in (d.get("stringData") or {}).items():
                if v not in ("", PLACEHOLDER):
                    errors.append(f"Secret/{n}: key '{k}' holds a real-looking value; only '{PLACEHOLDER}' is allowed.")
            if d.get("data"):
                errors.append(f"Secret/{n}: 'data' values are not allowed in generated templates.")
        if kind == "Deployment":
            spec = d.get("spec", {})
            tmpl = spec.get("template", {})
            sel, tl = spec.get("selector", {}).get("matchLabels"), tmpl.get("metadata", {}).get("labels", {})
            if not sel or any(tl.get(k) != v for k, v in sel.items()):
                errors.append(f"Deployment/{n}: selector does not match the pod template labels.")
            pod = tmpl.get("spec", {})
            for flag in ("hostNetwork", "hostPID", "hostIPC"):
                if pod.get(flag):
                    errors.append(f"Deployment/{n}: {flag} is not allowed.")
            if any("hostPath" in v for v in pod.get("volumes", [])):
                errors.append(f"Deployment/{n}: hostPath volumes are not allowed.")
            for c in pod.get("containers", []):
                sc = c.get("securityContext", {})
                if sc.get("privileged"):
                    errors.append(f"Deployment/{n}: privileged containers are not allowed.")
                if sc.get("allowPrivilegeEscalation") is not False:
                    warnings.append(f"Deployment/{n}: allowPrivilegeEscalation is not disabled.")
                req, lim = c.get("resources", {}).get("requests"), c.get("resources", {}).get("limits")
                if not req or not lim:
                    errors.append(f"Deployment/{n}: container '{c.get('name')}' needs resource requests and limits.")
                else:
                    if _cpu_milli(req["cpu"]) > _cpu_milli(lim["cpu"]) or _mem_mi(req["memory"]) > _mem_mi(lim["memory"]):
                        errors.append(f"Deployment/{n}: requests exceed limits.")
                for probe in ("livenessProbe", "readinessProbe"):
                    if probe not in c:
                        warnings.append(f"Deployment/{n}: no {probe}.")
                img = c.get("image", "")
                if img.endswith(":latest") or ":" not in img.split("/")[-1]:
                    warnings.append(f"Deployment/{n}: image '{img}' is not pinned to a version tag.")
                for ef in c.get("envFrom", []):
                    ref = ef.get("configMapRef") or ef.get("secretRef") or {}
                    kind_ref = "ConfigMap" if "configMapRef" in ef else "Secret"
                    if (kind_ref, ref.get("name")) not in by_kind:
                        errors.append(f"Deployment/{n}: references missing {kind_ref} '{ref.get('name')}'.")
            for v in pod.get("volumes", []):
                claim = v.get("persistentVolumeClaim", {}).get("claimName")
                if claim and ("PersistentVolumeClaim", claim) not in by_kind:
                    errors.append(f"Deployment/{n}: references missing PVC '{claim}'.")
        if kind == "Service":
            dep = next((x for (k, _), x in by_kind.items() if k == "Deployment" and all(
                x["spec"]["template"]["metadata"]["labels"].get(a) == b for a, b in d["spec"]["selector"].items())), None)
            if not dep:
                errors.append(f"Service/{n}: selector matches no Deployment.")
        if kind == "Ingress":
            for rule in d["spec"].get("rules", []):
                for p in rule.get("http", {}).get("paths", []):
                    if ("Service", p["backend"]["service"]["name"]) not in by_kind:
                        errors.append(f"Ingress/{n}: backend Service '{p['backend']['service']['name']}' does not exist.")
        if kind == "HorizontalPodAutoscaler":
            tgt = d["spec"]["scaleTargetRef"]
            if (tgt["kind"], tgt["name"]) not in by_kind:
                errors.append(f"HPA/{n}: target {tgt['kind']}/{tgt['name']} does not exist.")
            if d["spec"]["minReplicas"] > d["spec"]["maxReplicas"]:
                errors.append(f"HPA/{n}: minReplicas exceeds maxReplicas.")
    checked = False
    if use_kubectl and not errors and yaml_text and which("kubectl"):
        try:
            p = runner(["kubectl", "apply", "--dry-run=client", "--validate=false", "-f", "-"], input=yaml_text,
                       capture_output=True, text=True, timeout=30)
            checked = True
            if p.returncode != 0:
                errors.append("kubectl dry-run: " + (p.stderr or p.stdout).strip()[-300:])
        except (OSError, subprocess.TimeoutExpired):
            warnings.append("kubectl could not be run; only the built-in checks were applied.")
    elif use_kubectl and not which("kubectl"):
        warnings.append("kubectl is not installed; only the built-in checks were applied.")
    return K8sValidation(ok=not errors, errors=errors, warnings=warnings, kubectl_checked=checked)


def apply_instructions(result: K8sResult, directory: str = "k8s", namespace: Optional[str] = None) -> list[str]:
    """Commands for the USER to run after reviewing. This tool never runs them."""
    ns = f" -n {namespace}" if namespace else ""
    steps = []
    if namespace:
        steps.append(f"kubectl create namespace {namespace}   # if it does not exist yet")
    secrets = [d["metadata"]["name"] for d in result.docs if d["kind"] == "Secret"]
    for s in secrets:
        steps.append(f"# edit {directory}/*/secret.yaml (replace {PLACEHOLDER}) or run: kubectl create secret generic {s}"
                     f"{ns} --from-literal=KEY=VALUE ...  (and delete the template)")
    steps.append(f"kubectl apply --dry-run=server -f {directory} -R{ns}   # review what would change")
    steps.append(f"kubectl apply -f {directory} -R{ns}")
    steps.append(f"kubectl rollout status deployment/<name>{ns}")
    return steps


# ----------------------------------------------------------------------------- writing
class K8sProtectionError(PermissionError):
    pass


def write_manifests(project_dir: Path | str, result: K8sResult, *, directory: str = "k8s", overwrite: bool = False
                    ) -> list[Path]:
    root = Path(project_dir).resolve()
    if directory != Path(directory).name or directory.startswith("."):
        raise PermissionError("directory must be a plain folder name")
    plan = {Path(directory) / rel: text for rel, text in result.files.items()}
    clashes = [str(p) for p in plan if (root / p).exists() or (root / p).is_symlink()]
    if clashes and not overwrite:
        raise K8sProtectionError("Refusing to overwrite existing file(s) without approval: " + ", ".join(clashes))
    written = []
    for rel, text in plan.items():
        target = root / rel
        ensure_within(root, target.parent)
        if target.is_symlink() or target.parent.is_symlink():
            raise PermissionError(f"Refusing to write through symlink: {target}")
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists():
            target.with_name(target.name + ".bak").write_text(target.read_text(encoding="utf-8"), encoding="utf-8")
        tmp = target.with_name("." + target.name + ".tmp")
        tmp.write_text(text, encoding="utf-8")
        os.replace(tmp, target)
        written.append(target)
    return written
